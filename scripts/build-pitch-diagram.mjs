// Builds src/lib/site/PitchDiagram.svelte from design/pitch-diagram.svg (landscape) and
// design/pitch-diagram-portrait.svg. Run `pnpm build:diagram` after editing either SVG;
// tests/pitch-diagram.test.ts fails when the component and the sources drift apart.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const SOURCES = { landscape: 'design/pitch-diagram.svg', portrait: 'design/pitch-diagram-portrait.svg' };
export const OUTPUT = 'src/lib/site/PitchDiagram.svelte';

// The SVG classes the component maps to theme tokens. Anything else would render unstyled.
const CLASSES = ['bg', 'card', 'ink', 'muted', 'primary', 'on-primary', 'soft', 'line', 'blocked', 'blocked-text'];

const HEADER =
	'<!-- Generated by scripts/build-pitch-diagram.mjs from design/pitch-diagram.svg and design/pitch-diagram-portrait.svg; edit those and run pnpm build:diagram. Landscape from lg up, portrait below. Colours map to the console theme tokens, so dark mode follows the theme switch. -->';

const STYLE = `<style>
	svg { font-family: inherit; }
	.bg { fill: var(--card); }
	.card { fill: var(--background); stroke: var(--border); }
	.ink { fill: var(--foreground); }
	.muted { fill: var(--muted-foreground); }
	.primary { fill: var(--primary); }
	.on-primary { fill: var(--primary-foreground); }
	.soft { fill: var(--muted); }
	.line { stroke: var(--primary); fill: none; }
	.blocked { stroke: var(--destructive); fill: none; }
	.blocked-text { fill: var(--destructive); }
</style>
`;

/**
 * One source SVG as inline markup: checked, own <style> dropped, ids prefixed, layout class added.
 * @param {string} src @param {string} prefix @param {string} cls
 */
function inline(src, prefix, cls) {
	for (const bad of ['<script', 'href', 'foreignObject', '<image']) {
		if (src.includes(bad)) throw new Error(`${prefix}: ${bad} is not allowed`);
	}
	if (/\son[a-z]+=/.test(src)) throw new Error(`${prefix}: event handler attributes are not allowed`);
	for (const [, cl] of src.matchAll(/class="([^"]*)"/g)) {
		if (!CLASSES.includes(cl)) throw new Error(`${prefix}: unknown class "${cl}"`);
	}
	let out = src.replace(/\s*<style>[\s\S]*?<\/style>/g, '');
	out = out
		.replace('aria-labelledby="t d"', `aria-labelledby="${prefix}-title" aria-describedby="${prefix}-desc"`)
		.replace('id="t"', `id="${prefix}-title"`)
		.replace('id="d"', `id="${prefix}-desc"`)
		.replace('id="arrow"', `id="${prefix}-arrow"`)
		.replaceAll('url(#arrow)', `url(#${prefix}-arrow)`);
	if (out.includes('#arrow') || out.includes('id="t"') || out.includes('id="d"')) {
		throw new Error(`${prefix}: unexpected ids`);
	}
	return out.replace('<svg ', `<svg class="${cls}" `).trim();
}

/**
 * The component text for the given landscape and portrait sources.
 * @param {string} landscape @param {string} portrait
 */
export function buildPitchDiagram(landscape, portrait) {
	const land = inline(landscape, 'pitch', 'hidden h-auto w-full lg:block');
	const port = inline(portrait, 'pitch-portrait', 'mx-auto block h-auto w-full max-w-[480px] lg:hidden');
	return `${HEADER}\n${land}\n${port}\n\n${STYLE}`;
}

/** @returns {[string, string]} */
export function readSources(root = ROOT) {
	return [readFileSync(root + SOURCES.landscape, 'utf8'), readFileSync(root + SOURCES.portrait, 'utf8')];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(ROOT + OUTPUT, buildPitchDiagram(...readSources()));
	console.log(`wrote ${OUTPUT}`);
}
